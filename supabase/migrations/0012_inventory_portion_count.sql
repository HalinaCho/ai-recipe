-- ---------------------------------------------------------------------------
-- FR-04-09: 재고 한 행이 몇 끼분인지.
--
-- 지금까지 재고 한 행은 "한 번 쓰면 사라지는 것"이었다. 그런데 레시피는
-- 1인분 기준이고 한 끼에 양파 5g·대파 10g씩 쓴다. 양파 한 망을 한 끼에 다
-- 썼다고 치면 재고 아홉 줄이 요리 다섯 개 만에 바닥나고, 그 뒤 식단표가
-- 통째로 0%가 된다 (실측: 0% 요리 71%).
--
-- null = 아직 안 물어봤거나 물어볼 필요가 없는 표기. 이때는 수량 표기에서
-- 개수를 읽어 보고("6개" → 6), 그것도 안 되면 1끼분으로 본다.
-- 모르는 값을 넉넉히 잡으면 있지도 않은 재료로 식단표를 채우게 되는데,
-- 그건 장 보러 가서야 알게 되는 종류의 거짓말이다.
-- ---------------------------------------------------------------------------

alter table inventory_item add column portion_count integer
  check (portion_count is null or (portion_count >= 1 and portion_count <= 50));
