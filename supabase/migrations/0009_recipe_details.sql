-- ---------------------------------------------------------------------------
-- FR-07-03 / FR-06-04: 지금까지 버리고 있던 원본 데이터를 되살린다.
--
-- 사진 건과 같은 종류의 누락이 재료 쪽에도 있었다. 우리는 재료 원문
-- (RCP_PARTS_DTLS)을 LLM에 넣어 "정규화된 이름 + 역할"만 얻고 원문을 버렸는데,
-- 원문에는 계량이 100% 들어 있었다("연두부 75g(3/4모)"). 재료가 이름만 죽
-- 나열되면 뭘 얼마나 사야 하는지 알 수 없다.
--
-- 함께 확인된 미사용 필드도 이번에 같이 받는다 — 나중에 필요해졌을 때
-- 1,156건을 또 훑는 것보다 지금 한 번에 채우는 편이 훨씬 싸다.
-- ---------------------------------------------------------------------------

-- 재료 원문. 파싱이 틀렸을 때 사용자가 확인할 수 있는 최종 근거이자,
-- 나중에 파서를 고쳤을 때 외부 API를 다시 부르지 않고 재파싱할 수 있는
-- 원본이다. 파싱 결과만 저장하고 원문을 버리면 그 두 가지를 다 잃는다.
alter table recipe add column ingredients_text text;

-- RCP_NA_TIP — 나트륨 저감 조리 팁. 95%가 채워져 있고 내용이 실제로 쓸모
-- 있다("칼륨이 풍부한 시금치와 … 소금 대신 새우로 감칠맛을 냈다").
alter table recipe add column tip text;

-- INFO_WGT — 1인분 중량(g). 25%만 채워져 있지만, 영양정보 카드가 지금
-- "1인분 기준이에요"라고만 말하는 것을 "1인분 250g 기준"으로 구체화할 수 있다.
alter table recipe add column serving_weight numeric;

-- 재료별 계량과 그룹.
--
-- amount는 원문 표기를 **문자 그대로** 담는다("75g(3/4모)"). 숫자와 단위로
-- 쪼개지 않는 이유는 FR-05-04와 같다 — 단위 환산을 하지 않기로 했으므로
-- 쪼개 봤자 쓸 데가 없고, 쪼개는 순간 "1½컵"이나 "5마리" 같은 표기에서
-- 정보가 깎인다.
alter table recipe_ingredient add column amount text;

-- group_name은 "육수" · "고명" · "고기 밑간" 같은 원문 그룹. 원문에 그룹이
-- 있는 경우가 17%뿐이라 대부분 null이며, null이면 화면이 한 덩어리로 보여준다.
alter table recipe_ingredient add column group_name text;
