-- ---------------------------------------------------------------------------
-- FR-13-06: 끼니 레시피와 간식(후식) 레시피를 구분한다.
--
-- 재고가 바닥난 요일에 "건강 마늘 꿀환"이 저녁으로 배치되는 문제에서 출발했다.
-- 매칭률이 전부 0으로 동점이 되면 이름순으로 갈리는데, 그 틈으로 끼니가 아닌
-- 것들이 올라온다.
--
-- 직접 규칙을 만들 필요는 없었다 — 식약처 원본에 이미 RCP_PAT2(요리종류)가
-- 있고 "후식"이 142건으로 분류되어 있다. 우리가 그 필드를 안 가져오고 있었을
-- 뿐이다. 추론 대신 원본 분류를 그대로 쓴다.
-- ---------------------------------------------------------------------------

-- RCP_PAT2 원문을 그대로 담는다 (반찬 / 일품 / 후식 / 밥 / 국&찌개 / 기타).
-- 값을 앱에서 정한 enum으로 번역해 넣지 않는 이유: 소스가 분류를 늘리거나
-- 이름을 바꿨을 때, 번역 테이블에 없는 값이 조용히 기본값으로 뭉개지는 것보다
-- 원문이 남아 있는 편이 낫다. 끼니/간식 판정은 앱 코드가 한다.
alter table recipe add column category text;

-- RCP_WAY2(조리방법: 굽기/끓이기/찌기/…). 지금 당장 쓰지는 않지만 같은
-- 백필 한 번에 같이 채워 둔다 — 나중에 필요해졌을 때 1,156건을 다시
-- 훑는 것보다 지금 한 컬럼 더 받는 비용이 훨씬 싸다.
alter table recipe add column cooking_method text;

-- 후보 풀을 뽑을 때 "간식 빼고"가 매 조회에 붙는다.
create index recipe_category_idx on recipe (category);
