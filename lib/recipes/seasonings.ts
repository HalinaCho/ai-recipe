/**
 * 정규화된 재료명이 조미료 화이트리스트에 걸리는지 본다.
 * 표기 흔들림("다진 마늘" vs "다진마늘")을 흡수하려고 공백을 지우고 비교한다.
 */
export function isWhitelistedSeasoning(normalizedName: string): boolean {
  const needle = normalizedName.replace(/\s+/g, "");
  return SEASONING_WHITELIST.some(
    (seasoning) => seasoning.replace(/\s+/g, "") === needle,
  );
}
