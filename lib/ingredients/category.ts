const seedCategoryByName = new Map(
  INGREDIENT_ICON_SEED.map((entry) => [entry.normalizedName, entry.category]),
);

/**
 * 정규화된 재료명을 대분류로 묶는다.
 *
 * 우선순위:
 *   ① 조미료 화이트리스트(FR-07-02) — 매칭에서 빼는 것과 같은 목록을 쓴다.
 *   ② `INGREDIENT_ICON_SEED`의 명시적 매핑 — 아이콘과 축이 갈리지 않게.
 *   ③ 이름 패턴 규칙
 *   ④ "other"
 *
 * 표기 흔들림("다진 마늘" vs "다진마늘")을 흡수하려고 공백을 지우고 본다 —
 * seasonings.ts의 비교 방식과 같다.
 */
export function resolveCategory(normalizedName: string): IngredientCategory {
  const name = normalizedName.replace(/\s+/g, "");
  if (name.length === 0) return "other";

  if (isWhitelistedSeasoning(name)) return "seasoning";

  const seeded = seedCategoryByName.get(normalizedName) ?? seedCategoryByName.get(name);
  if (seeded) return seeded;

  for (const rule of CATEGORY_RULES) {
    if (rule.pattern.test(name)) return rule.category;
  }

  return "other";
}

/**
 * 여러 재료의 카테고리 비중. 합이 1이 되며, 재료가 없으면 빈 Map이다.
 * 다양성 보너스가 "최근 구매의 카테고리 비중"을 필요로 해서 여기 둔다 —
 * 분류 규칙과 집계가 떨어져 있으면 한쪽만 고쳐 어긋나기 쉽다.
 */
export function categoryShares(
  normalizedNames: readonly string[],
  countedCategories: readonly IngredientCategory[],
): Map<IngredientCategory, number> {
  const allowed = new Set(countedCategories);
  const counts = new Map<IngredientCategory, number>();
  let total = 0;

  for (const name of normalizedNames) {
    const category = resolveCategory(name);
    if (!allowed.has(category)) continue;
    counts.set(category, (counts.get(category) ?? 0) + 1);
    total += 1;
  }

  if (total === 0) return new Map();

  const shares = new Map<IngredientCategory, number>();
  for (const [category, count] of counts) {
    shares.set(category, count / total);
  }
  return shares;
}
