/** Asia/Seoul 기준 현재 월. */
export function currentMonthInSeoul(now: Date = new Date()): Month {
  const seoul = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Seoul",
    month: "numeric",
  }).format(now);
  return Number(seoul);
}

/** YYYY-MM-DD에서 월을 뽑는다. */
export function monthOf(date: string): Month {
  return Number(date.slice(5, 7));
}

/**
 * 이 재료가 해당 월에 제철인가.
 * 목록에 없으면 계절을 안 타는 재료로 보고 언제나 true.
 */
export function isInSeason(normalizedName: string, month: Month): boolean {
  const months = SEASONAL_MONTHS[normalizedName.trim()];
  if (!months) return true;
  return months.includes(month);
}

/** 계절을 타는 재료로 등록되어 있는가 (제철 여부와 무관). */
export function isSeasonalIngredient(normalizedName: string): boolean {
  return normalizedName.trim() in SEASONAL_MONTHS;
}

/**
 * 이 달에 **사러 가면 안 되는** 재료를 골라낸다.
 *
 * 이미 갖고 있는 재료는 제외하는 것이 이 함수의 핵심이다. 8월에 냉장고에
 * 감귤이 있다면 그건 먹어 없애야 할 재고지 말려야 할 구매가 아니다.
 * 제철 감점을 보유 재료에까지 물리면, 재고를 비우라는 서비스의 목적(FR-04-02)과
 * 정면으로 부딪힌다.
 */
export function outOfSeasonPurchases(
  missingIngredients: readonly string[],
  month: Month,
): string[] {
  return missingIngredients.filter((name) => !isInSeason(name, month));
}

/**
 * 하나라도 제철이 아니면 붙는 기본 감점의 몫 (0~1).
 *
 * 비율만으로 깎으면 재료가 많은 레시피에서 감점이 희석된다. 실제로
 * "감귤콩샐러드"는 주재료가 8개라 감귤 하나가 제철이 아니어도 비율이 1/8뿐이라
 * 계수가 0.88까지밖에 안 떨어졌다. 그런데 이 요리는 **감귤이 주인공**이다 —
 * 재료 가짓수가 많다는 이유로 제철 판단이 무뎌지는 건 말이 안 된다.
 *
 * 그래서 감점의 절반은 "제철 아닌 걸 사야 한다"는 사실 자체에 붙이고,
 * 나머지 절반만 비율에 비례시킨다.
 */
const BASE_SHARE = 0.5;

/**
 * 제철 감점 계수 (0~1, 1이면 감점 없음).
 *
 * 완전 배제가 아니라 감점인 이유는 FR-13-03 때문이다 — 빈 칸을 만들지
 * 않으려면 후보가 마르면 안 되고, 제철 아닌 것이 정말 유일한 선택지라면
 * 배치되는 편이 낫다. 다만 대안이 하나라도 있으면 확실히 밀려날 만큼은 깎는다.
 *
 * strength 0.7 기준:
 *   - 주재료 8개 중 1개가 제철 아님 → 계수 0.61
 *   - 주재료 전부가 제철 아님       → 계수 0.30
 */
export function seasonPenaltyFactor(
  mainIngredientNames: readonly string[],
  missingIngredients: readonly string[],
  month: Month,
  strength = 0.7,
): number {
  if (mainIngredientNames.length === 0) return 1;
  const offenders = outOfSeasonPurchases(missingIngredients, month);
  if (offenders.length === 0) return 1;
  const ratio = Math.min(
    1,
    offenders.length / mainIngredientNames.length,
  );
  const penalty = strength * (BASE_SHARE + (1 - BASE_SHARE) * ratio);
  return Math.max(0, 1 - penalty);
}
